//! Canonical model documents and ModelHash (contract `identity-and-source-map.md`).
//!
//! ```text
//! ModelHash(M) = tagged_hash("behavior.model.v1", CanonicalModelDocument(M))
//! ```
//!
//! The document holds only semantic facts: sets are sorted arrays, parameter mappings are
//! sorted by name, and every Core fragment is represented by Core's own semantic hash, read
//! from the admitted generated action at the positions the lowering layout fixes. Display
//! metadata, source locations, the lowerer version and generated names are never part of it.

use behavior_engine::canonical::tagged_hash;
use behavior_engine::semantic::Module;
use behavior_engine::semantic::types::hash_display;
use serde_json::{Value, json};

use crate::composition::Composed;
use crate::error::ModelError;
use crate::source_map::{Diagnostic, LoweringReceipt, diagnostics, receipt};
use crate::state_machine::resolve::ResolvedStateMachine;
use crate::{STATE_MACHINE_SEMANTIC_VERSION, composition::admission_failed_message};

pub const MODEL_HASH_TAG: &str = "behavior.model.v1";

pub(crate) fn identity_error(message: String) -> ModelError {
    admission_failed_message("MODEL_IDENTITY_FAILED", message)
}

pub(crate) fn params(
    m: &std::collections::BTreeMap<String, behavior_engine::wire::WType>,
) -> Result<Value, ModelError> {
    m.iter()
        .map(|(name, ty)| {
            let ty = serde_json::to_value(ty).map_err(|e| identity_error(e.to_string()))?;
            Ok(json!({"name": name, "type": ty}))
        })
        .collect::<Result<Vec<_>, _>>()
        .map(Value::Array)
}

/// The canonical document of a resolved, lowered and admitted state machine.
pub fn canonical_document(m: &ResolvedStateMachine, module: &Module) -> Result<Value, ModelError> {
    let enum_hash = module
        .enums()
        .get(&m.enum_type)
        .map(|e| hash_display(&e.hash))
        .ok_or_else(|| identity_error(format!("enum `{}` not in module", m.enum_type)))?;
    let mut transitions = Vec::new();
    for t in m.transitions.values() {
        let action = module
            .actions()
            .get(&t.action_name)
            .ok_or_else(|| identity_error(format!("action `{}` not in module", t.action_name)))?;
        // Fragment identities at their layout positions (lowering contract §3): the first
        // precondition, effect and postcondition are generated by the machine.
        let guards: Vec<String> = action
            .preconditions()
            .iter()
            .skip(1)
            .map(|c| hash_display(c.expr().hash()))
            .collect();
        let effects: Vec<String> = action
            .effects()
            .iter()
            .skip(1)
            .map(|e| hash_display(e.hash()))
            .collect();
        let post: Vec<String> = action
            .postconditions()
            .iter()
            .skip(1)
            .map(|c| hash_display(c.expr().hash()))
            .collect();
        let commands: Vec<String> = action
            .command_emissions()
            .iter()
            .map(|c| hash_display(c.hash()))
            .collect();
        transitions.push(json!({
            "id": t.transition_id.as_str(),
            "from": t.from_states,
            "to": t.to_state,
            "inputs": params(&t.inputs)?,
            "context": params(&t.context)?,
            "guards": guards,
            "effects": effects,
            "postconditions": post,
            "commands": commands,
        }));
    }
    Ok(json!({
        "format": "behavior.model.state_machine.v1",
        "model_kind": "state_machine",
        "model_semantic_version": STATE_MACHINE_SEMANTIC_VERSION,
        "model_id": m.model_id.as_str(),
        "subject": {"entity": m.subject},
        "field": {"name": m.field, "enum": m.enum_type, "enum_hash": enum_hash},
        "subject_param": m.subject_param,
        "entry_states": m.entry_states,
        "transitions": transitions,
    }))
}

/// `ModelHash` of a canonical document: `sha256:<hex>`.
pub fn model_hash(document: &Value) -> Result<String, ModelError> {
    tagged_hash(MODEL_HASH_TAG, document).map_err(|e| identity_error(e.to_string()))
}

/// Receipts (one per model, in model-id order) and diagnostics of a successful build.
pub(crate) fn outputs(
    module: &Module,
    composed: &[Composed],
    root: Option<&str>,
) -> Result<(Vec<LoweringReceipt>, Vec<Diagnostic>), Vec<ModelError>> {
    let mut receipts = Vec::new();
    let mut diags = Vec::new();
    for c in composed {
        // Every machine is diagnosed; only supplied machines get a receipt (derived machines
        // are recorded inside their parent model's receipt).
        diags.extend(diagnostics(&c.machine, module));
        if !c.supplied {
            continue;
        }
        let doc = canonical_document(&c.machine, module).map_err(|e| vec![e])?;
        let hash = model_hash(&doc).map_err(|e| vec![e])?;
        receipts.push(receipt(module, &c.machine, doc, hash, root));
    }
    diags.sort();
    Ok((receipts, diags))
}
